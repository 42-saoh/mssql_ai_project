CREATE PROCEDURE dbo.usp_OrderSave
    @ORDER_ID BIGINT,
    @CUSTOMER_ID BIGINT
AS
BEGIN
    SET NOCOUNT ON;
    BEGIN TRY
        BEGIN TRANSACTION;

        INSERT INTO dbo.TB_ORDER (ORDER_ID, CUSTOMER_ID)
        VALUES (@ORDER_ID, @CUSTOMER_ID);

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;
        THROW;
    END CATCH
END
